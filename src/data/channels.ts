// Helper function to get channel by ID
export function getChannelById(id: string): Channel | undefined {
  return channels.find(c => c.id === id);
}

// Helper function to get channels by category
export function getChannelsByCategory(category: string): Channel[] {
  // This is a simplified categorization
  const categories: Record<string, string[]> = {
    'organic': ['seo', 'content_marketing', 'organic_linkedin', 'podcasts', 'communities'],
    'paid': ['paid_linkedin', 'google_search'],
    'outbound': ['cold_email', 'founder_outbound'],
    'events': ['webinars', 'events'],
    'partnerships': ['partner_marketing', 'referral_program'],
    'product': ['plg'],
    'abm': ['abm']
  };
  
  return channels.filter(c => categories[category]?.includes(c.id));
}
