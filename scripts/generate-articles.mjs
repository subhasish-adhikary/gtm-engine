/*
 * Sanity -> website data generator.
 *
 * Queries published articles from the Content Lake and writes
 * src/data/articles.generated.ts, which src/data/articles.ts serves as the
 * site's article source. When Sanity is unreachable/empty (e.g. dataset not
 * created yet), the file is written empty and the site falls back to the
 * legacy TypeScript articles — the build never breaks on CMS issues.
 *
 * Runs at the start of `npm run build`; also runnable standalone.
 * Read-only: no tokens, CDN/public perspective only.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {createJiti} from 'jiti';

const require = createRequire(import.meta.url);
const {createClient} = require('@sanity/client');
const jiti = createJiti(import.meta.url);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const outFile = path.join(root, 'src/data/articles.generated.ts');

const PROJECT_ID = '0uqx6fxe';
const DATASET = 'production';

const QUERY = `*[_type == "article" && defined(slug.current)] | order(publishedDate desc) {
  _id, title, "slug": slug, category, thesis, author, authorBio,
  publishedDate, updatedDate, readingTime,
  "featuredImage": featuredImage{asset}, featuredImageAlt,
  atAGlance, tableOfContents, content, faq, sources,
  "relatedArticles": relatedArticles[]{_ref}, relatedTools, legacyId
}`;

async function main() {
  let docs = [];
  let source = 'none';

  try {
    const client = createClient({
      projectId: PROJECT_ID,
      dataset: DATASET,
      apiVersion: '2024-10-01',
      // Build-time reads must be fresh (a deploy should pick up newly
      // published articles immediately, not wait for CDN propagation).
      useCdn: false,
      perspective: 'published',
    });
    docs = await client.fetch(QUERY);
    source = 'sanity';
    console.log(`✓ Sanity: fetched ${docs.length} published article(s)`);
  } catch (err) {
    console.warn(`⚠ Sanity fetch failed (${String(err).split('\n')[0]}) — falling back to legacy articles`);
  }

  // Map Sanity docs -> Article shape; resolve related-article refs to slugs.
  let articles = [];
  if (docs.length > 0) {
    const {sanityArticleToArticle} = await jiti.import('../src/data/sanity/articleMapping.ts');
    const idToSlug = new Map(docs.map((d) => [d._id, d.slug?.current || d.legacyId || d._id]));
    articles = docs
      .map((doc) => {
        const a = sanityArticleToArticle(doc);
        a.relatedArticles = (doc.relatedArticles || [])
          .map((r) => idToSlug.get(r._ref) || '')
          .filter(Boolean);
        return a;
      })
      .filter((a) => a.id && a.title && a.featuredImage);
    console.log(`✓ Mapped ${articles.length} article(s) for the website`);
  }

  const banner = `/**
 * GENERATED FILE — do not edit by hand.
 * Source: Sanity Content Lake (project ${PROJECT_ID}, dataset ${DATASET}, published perspective)
 * Regenerated by scripts/generate-articles.mjs on every build.
 * When empty, src/data/articles.ts falls back to the legacy TypeScript articles.
 */
`;

  const body =
    `import type {Article} from './articles';\n\n` +
    `export const generatedSource: 'sanity' | 'none' = ${JSON.stringify(source)};\n\n` +
    `export const generatedArticles: Article[] = ${JSON.stringify(articles, null, 2)};\n`;

  fs.writeFileSync(outFile, banner + body, 'utf8');
  console.log(`✓ Wrote ${outFile} (${articles.length} articles, source: ${source})`);

  if (source === 'sanity' && articles.length === 0) {
    console.warn('⚠ Sanity reachable but 0 published articles — site will use legacy articles until migration is run.');
  }
}

main().catch((err) => {
  console.error('generate-articles failed:', err);
  // Never break the deployment on CMS issues — write an empty fallback file.
  const banner = '/* GENERATED FILE — Sanity unavailable; using legacy articles. */\n';
  fs.writeFileSync(
    outFile,
    banner + `import type {Article} from './articles';\n\nexport const generatedSource: 'sanity' | 'none' = 'none';\n\nexport const generatedArticles: Article[] = [];\n`,
    'utf8'
  );
  process.exit(0);
});
